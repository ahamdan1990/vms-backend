    private readonly ILicenseStorageService _storage;
    private readonly IMachineFingerprintService _fingerprint;
    private readonly IHostEnvironment _environment;
    private readonly ILogger<LicenseValidatorService> _logger;

    private LicenseValidationResult _cachedResult = LicenseValidationResult.NotActivated();
    private readonly SemaphoreSlim _validateLock = new(1, 1);

    public LicenseValidatorService(
        ILicenseStorageService storage,
        IMachineFingerprintService fingerprint,
        IHostEnvironment environment,
        ILogger<LicenseValidatorService> logger)
    {
        _storage = storage;
        _fingerprint = fingerprint;
        _environment = environment;
        _logger = logger;
    }

    public LicenseValidationResult GetCachedResult() => _cachedResult;

    public void InvalidateCache() => _cachedResult = LicenseValidationResult.NotActivated();

    public async Task<LicenseValidationResult> ValidateCurrentLicenseAsync(CancellationToken ct = default)
    {
        // Dev mode: full bypass
        if (_environment.IsDevelopment())
        {
            _cachedResult = LicenseValidationResult.DevMode();
            return _cachedResult;
        }

        await _validateLock.WaitAsync(ct);
        try
        {
            var result = await RunAllChecksAsync(ct);
            _cachedResult = result;
            return result;
        }
        finally
        {
            _validateLock.Release();
        }
    }

    public async Task<LicenseValidationResult> ActivateLicenseAsync(byte[] licenseFileBytes, CancellationToken ct = default)
    {
        LicensePayload? payload;
        try
        {
            var json = Encoding.UTF8.GetString(licenseFileBytes);
            payload = System.Text.Json.JsonSerializer.Deserialize<LicensePayload>(json,
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
        }
        catch
        {
            return LicenseValidationResult.Failure(LicenseStatus.Invalid, "License file is not valid JSON.");
        }

        if (payload == null)
            return LicenseValidationResult.Failure(LicenseStatus.Invalid, "License file is empty.");

        // Run signature + hardware checks before storing
        var tempResult = await ValidatePayloadAsync(payload, ct);
        if (!tempResult.IsValid)
            return tempResult;

        // Store (DPAPI + Registry + DB)
        await _storage.StoreLicenseAsync(payload, ct);

        var scores = _fingerprint.ScoreAgainstLicense(payload.MachineFingerprint);
        await _storage.UpdateDatabaseRecordAsync(payload, scores, null, ct);

        _cachedResult = tempResult;
        _logger.LogInformation("License activated for {Email} (ID: {LicenseId}, Type: {Type})",
            payload.CustomerEmail, payload.LicenseId, payload.LicenseType);

        return tempResult;
    }

    public async Task DeactivateAsync(CancellationToken ct = default)
    {
        await _storage.ClearLicenseAsync(ct);
        _cachedResult = LicenseValidationResult.NotActivated();
        _logger.LogInformation("License deactivated.");
    }

