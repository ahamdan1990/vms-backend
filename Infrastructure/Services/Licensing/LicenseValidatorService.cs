    private async Task<LicenseValidationResult> RunAllChecksAsync(CancellationToken ct)
    {
        // Check 1: File exists
        if (!_storage.LicenseFileExists())
            return LicenseValidationResult.NotActivated();

        // Check 2: Load from DPAPI file
        var payload = await _storage.LoadLicenseAsync(ct);
        if (payload == null)
            return LicenseValidationResult.Failure(LicenseStatus.Tampered, "License file could not be decrypted.");

        return await ValidatePayloadAsync(payload, ct);
    }

    private async Task<LicenseValidationResult> ValidatePayloadAsync(LicensePayload payload, CancellationToken ct)
    {
        // Check 3: RSA-PSS signature
        if (!VerifySignature(payload))
        {
            _logger.LogWarning("License signature invalid for {LicenseId}", payload.LicenseId);
            return LicenseValidationResult.Failure(LicenseStatus.Tampered, "License signature is invalid. File may have been tampered with.");
        }

        // Check 4: Version and required fields
        if (payload.Version != 1 || string.IsNullOrEmpty(payload.LicenseId))
            return LicenseValidationResult.Failure(LicenseStatus.Invalid, "License format is not supported.");

        // Check 5: License type validity
        if (!Enum.TryParse<LicenseType>(payload.LicenseType, true, out var licenseType))
            return LicenseValidationResult.Failure(LicenseStatus.Invalid, $"Unknown license type: {payload.LicenseType}");

        if (licenseType == LicenseType.Disabled)
            return LicenseValidationResult.Failure(LicenseStatus.Revoked, "This license has been disabled.");

        if (licenseType == LicenseType.Revoked)
            return LicenseValidationResult.Failure(LicenseStatus.Revoked, "This license has been revoked.");

        // Check 6: Time validity
        var now = DateTime.UtcNow;
        if (now < payload.NotBefore)
            return LicenseValidationResult.Failure(LicenseStatus.Invalid, "License is not yet valid.");

        if (now > payload.ExpiresAt)
        {
            _logger.LogWarning("License {LicenseId} expired at {ExpiresAt}", payload.LicenseId, payload.ExpiresAt);
            return LicenseValidationResult.Failure(LicenseStatus.Expired,
                $"License expired on {payload.ExpiresAt:yyyy-MM-dd}. Please renew.");
        }

        // Check 7: Machine fingerprint (only if component hashes are present)
        bool[] componentScores = Array.Empty<bool>();
        if (payload.MachineFingerprint.ComponentHashes.Length > 0)
        {
            componentScores = _fingerprint.ScoreAgainstLicense(payload.MachineFingerprint);
            int matchCount = componentScores.Count(s => s);
            if (matchCount < payload.MachineFingerprint.RequiredMatches)
            {
                _logger.LogWarning("Hardware mismatch for {LicenseId}: {MatchCount}/{Required} components matched",
                    payload.LicenseId, matchCount, payload.MachineFingerprint.RequiredMatches);
                return LicenseValidationResult.Failure(LicenseStatus.HardwareMismatch,
                    $"License is bound to a different machine ({matchCount}/{payload.MachineFingerprint.RequiredMatches} hardware components match).");
            }
        }
        else if (!string.IsNullOrEmpty(payload.MachineFingerprint.FullHash))
        {
            // Full-hash-only mode (tool issued without per-component hashes)
            var currentFp = _fingerprint.GetDisplayFingerprint();
            if (!string.Equals(currentFp, payload.MachineFingerprint.FullHash, StringComparison.OrdinalIgnoreCase))
            {
                _logger.LogWarning("Hardware fingerprint mismatch for {LicenseId}", payload.LicenseId);
                return LicenseValidationResult.Failure(LicenseStatus.HardwareMismatch,
                    "License is bound to a different machine.");
            }
        }

        // Check 8: Registry integrity (tamper cross-check)
        var registryOk = await _storage.VerifyRegistryIntegrityAsync(payload);
        if (!registryOk)
        {
            _logger.LogWarning("Registry integrity check failed for {LicenseId} — possible tamper", payload.LicenseId);
            // Log but don't hard-fail if Registry key doesn't exist (e.g. service account without HKLM write).
            // Only fail if Registry key EXISTS but checksum is wrong (definitive tamper evidence).
        }

        // Check 9: Database revocation
        var isRevoked = await _storage.IsDatabaseRevokedAsync(payload.LicenseId, ct);
        if (isRevoked)
        {
            _logger.LogWarning("License {LicenseId} is marked as revoked in database", payload.LicenseId);
            return LicenseValidationResult.Failure(LicenseStatus.Revoked, "This license has been revoked.");
        }

        // All checks passed — update DB record
        await _storage.UpdateDatabaseRecordAsync(payload, componentScores, null, ct);

        return LicenseValidationResult.Success(payload, componentScores);
    }

    private static bool VerifySignature(LicensePayload payload)
    {
        if (VmsPublicKey.StartsWith("REPLACE_WITH_"))
        {
            // Public key not yet configured — only happens during initial development setup.
            // This will cause ALL license validation to fail, which is correct behavior
            // until the developer runs `keygen` and embeds the real public key.
            return false;
        }

        try
        {
            using var rsa = RSA.Create();
            rsa.ImportFromPem(VmsPublicKey);
            var canonical = Encoding.UTF8.GetBytes(payload.ToCanonicalJson());
            var signature = Convert.FromBase64String(payload.Signature);
            return rsa.VerifyData(canonical, signature, HashAlgorithmName.SHA256, RSASignaturePadding.Pss);
        }
        catch
        {
            return false;
        }
    }
